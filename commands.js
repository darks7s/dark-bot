export function matchCommand(text, list) {
  if (!text) return false
  const clean = text.replace(/^[.\/!#*]/, '').trim().toLowerCase()
  return list.some(cmd => {
    const c = cmd.toLowerCase()
    return clean === c || clean.startsWith(c + ' ')
  })
}

